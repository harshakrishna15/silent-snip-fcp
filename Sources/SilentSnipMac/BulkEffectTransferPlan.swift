import Foundation
import SilentSnipCore
#if canImport(FoundationXML)
import FoundationXML
#endif

/// A bulk XML edit whose original native effects are transferred separately.
/// Only `effectFreeOutput.xmlData` may be imported. `expectedXML` describes the
/// final serialized state after native Paste Attributes and is verification
/// evidence, never permission to reconstruct incomplete effect state from XML.
struct BulkEffectTransferPlan: Sendable {
    struct Effect: Equatable, Sendable {
        let name: String
        let uid: String
        let enabled: Bool
    }

    let sourcePlan: NativeSourceEditPlan
    let effectFreeOutput: EditedProjectOutput
    let expectedXML: Data
    let effects: [Effect]
    let sourceTargetName: String

    var effectNames: [String] { effects.map(\.name) }

    static func make(projectData: Data, selection: TimelineSelection,
                     cuts: [TimeRange], outputName: String,
                     projectUID: UUID = UUID()) throws -> BulkEffectTransferPlan {
        // This validates bounded XML, original library/event/project identity,
        // normal source timing, complete audio-only topology and every cut.
        let source = try NativeSourceEditPlan.makeBulk(projectData: projectData,
            selection: selection, removals: cuts)
        let xml = try XMLDocument(data: projectData, options: [.nodeLoadExternalEntitiesNever])
        guard let clip = try xml.nodes(forXPath: "/fcpxml/library/event/project/sequence/spine/asset-clip").first as? XMLElement,
              let resources = xml.rootElement()?.elements(forName: "resources").first else {
            throw unsupported("the reviewed original audio clip is missing")
        }
        let filters = clip.elements(forName: "filter-audio")
        let allFilters = try clip.nodes(forXPath: ".//filter-audio")
        guard !filters.isEmpty, filters.count == allFilters.count else {
            throw unsupported("bulk effect transfer requires effects directly on the original clip; component-level effects are not supported")
        }
        let resourcesByID = Dictionary(grouping: resources.elements(forName: "effect"),
            by: { $0.attribute(forName: "id")?.stringValue ?? "" })
        var effects: [Effect] = []
        for filter in filters {
            // Maintain/Stretch do not establish original source-time alignment
            // for many independently shortened recipients. Static native state
            // is transferable without retiming an effect's automation curve.
            guard try filter.nodes(forXPath: ".//keyframeAnimation").isEmpty else {
                throw unsupported("animated audio effects require a verified source-time transfer; this bulk route supports static effect settings")
            }
            guard let ref = nonempty(filter, "ref"),
                  let matches = resourcesByID[ref], matches.count == 1,
                  let resource = matches.first, let uid = nonempty(resource, "uid"),
                  uid != AudioControllerSettings.effectUID,
                  let name = nonempty(filter, "nameOverride") ?? nonempty(filter, "name") ?? nonempty(resource, "name") else {
                throw unsupported("every transferred effect must identify its original native instance and display name")
            }
            let enabled = filter.attribute(forName: "enabled")?.stringValue ?? "1"
            guard ["0", "1"].contains(enabled) else {
                throw unsupported("an audio effect has an invalid enabled state")
            }
            effects.append(.init(name: name, uid: uid, enabled: enabled == "1"))
        }
        // The imported result starts with no effects. Pasting onto copied bare
        // filters could duplicate chains or retain reset wrapper defaults.
        for filter in filters { filter.detach() }
        let remainingRefs = Set(try xml.nodes(forXPath: "//*[@ref]").compactMap {
            ($0 as? XMLElement)?.attribute(forName: "ref")?.stringValue
        })
        for effect in resources.elements(forName: "effect") {
            if let id = effect.attribute(forName: "id")?.stringValue, !remainingRefs.contains(id) {
                effect.detach()
            }
        }
        let stripped = xml.xmlData
        try EditableEffectReconstruction.validate(projectData: stripped)
        // Keep the ordinary writer's effect reconstruction guard intact. These
        // are the only generated bytes the import route is allowed to deliver.
        let imported = try EditedProjectWriter.write(projectData: stripped,
            selection: selection, selectedRanges: source.removals,
            outputName: outputName, projectUID: projectUID,
            destinationLibrary: source.libraryURL, selectedClipOnly: false,
            useOriginalEvent: true, omitController: true)
        let expected = try EditedProjectWriter.nativeEditExpectation(projectData: projectData,
            selection: selection, selectedRanges: source.removals,
            outputName: outputName, projectUID: imported.report.projectUID)
        // Both routes use the established writer. Check their independent
        // geometry reports rather than comparing the intentionally different DSP.
        guard imported.report.retainedSegments == expected.report.retainedSegments,
              imported.report.resultProjectDuration == source.final.duration,
              imported.report.projectUID == expected.report.projectUID,
              imported.report.eventUID == expected.report.eventUID else {
            throw EditedProjectWriterError.verificationFailed("the bulk import and native-effect expectation disagree on the retained source intervals")
        }
        return .init(sourcePlan: source, effectFreeOutput: imported,
            expectedXML: expected.xmlData, effects: effects, sourceTargetName: source.target.name)
    }

    private static func nonempty(_ node: XMLElement, _ name: String) -> String? {
        guard let value = node.attribute(forName: name)?.stringValue,
              !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              value.utf8.count <= 1_024 else { return nil }
        return value
    }

    private static func unsupported(_ message: String) -> EditedProjectWriterError {
        .unsupported(message)
    }
}
